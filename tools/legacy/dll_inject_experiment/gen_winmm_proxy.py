# -*- coding: utf-8 -*-
"""生成 winmm 代理转发桩。

从系统 winmm.dll 读取全部导出名，生成：
  winmm_forward.asm —— 每个导出一个 `jmp DWORD PTR [p_x]` 转发桩
  winmm_forward.cpp —— 声明符号 + WinmmProxyInit() 解析真实地址
  winmm_forward.def —— 导出表

为什么必须用 MASM 而不是 C++ 包装函数：
winmm 多数导出带参数（x86 下调用方压栈）。若写成
    void foo() { ((void(*)())p_foo)(); }
包装函数不接收参数、也不调整栈，转发时栈错位，被调用方读到错乱的
参数（甚至跳进栈里的数据），Chromium 一调用就崩。
`jmp` 不动物理栈，参数原样传给真实实现——这是唯一安全的转发方式。
"""
import os, struct, sys


def read_exports(path):
    d = open(path, 'rb').read()
    pe_off = struct.unpack_from('<I', d, 0x3c)[0]
    assert d[pe_off:pe_off + 4] == b'PE\0\0'
    coff = pe_off + 4
    nsec = struct.unpack_from('<H', d, coff + 2)[0]
    opt_size = struct.unpack_from('<H', d, coff + 16)[0]
    opt = coff + 20
    magic = struct.unpack_from('<H', d, opt)[0]
    dd = opt + (112 if magic == 0x20b else 96)
    exp_rva, _ = struct.unpack_from('<II', d, dd)
    sec = opt + opt_size
    sections = []
    for i in range(nsec):
        o = sec + i * 40
        vs, va, rsize, raddr = struct.unpack_from('<IIII', d, o + 8)
        sections.append((va, max(vs, rsize), raddr))

    def rva2off(rva):
        for va, size, raddr in sections:
            if va <= rva < va + size:
                return raddr + (rva - va)
        return None

    off = rva2off(exp_rva)
    (_, _, _, _, _, _, nfunc, nnames, _, addr_names, addr_ords) = \
        struct.unpack_from('<IIHHIIIIIII', d, off)
    no = rva2off(addr_names)
    oo = rva2off(addr_ords)
    names = []
    for i in range(nnames):
        nrva = struct.unpack_from('<I', d, no + i * 4)[0]
        n_off = rva2off(nrva)
        end = d.index(b'\0', n_off)
        nm = d[n_off:end].decode('ascii')
        ord_idx = struct.unpack_from('<H', d, oo + i * 2)[0]
        if ord_idx >= nfunc:      # 转发器/序号导出无需代理
            continue
        names.append(nm)
    return names


def main():
    sysdll = os.path.join(os.environ.get('SystemRoot', r'C:\Windows'),
                          'System32', 'winmm.dll')
    names = read_exports(sysdll)
    bad = set('return if else for while do switch case break continue default '
              'class struct new delete this nullptr true false'.split())
    names = [n for n in names if n not in bad]
    here = os.path.dirname(os.path.abspath(__file__))

    with open(os.path.join(here, 'winmm_forward.asm'), 'w',
              encoding='ascii', newline='\n') as f:
        f.write('; generated by tools/inject/gen_winmm_proxy.py - do not edit\n')
        f.write('; Plain jmp per export: caller stack (arguments) is preserved.\n')
        f.write('; 32-bit MASM: EXTERN_C unsupported by this ml build; exports come from .def\n'
                '.MODEL FLAT, STDCALL\n\n.DATA\n')
        for n in names:
            # 标签不带下划线：MASM 的 PUBLIC 会自动补 C 修饰前缀，
            # 最终符号名 _p_x 正好对上 C++ 侧 extern "C" 的引用
            f.write('PUBLIC p_%s\np_%s DD 0\n' % (n, n))
        f.write('.CODE\n')
        for n in names:
            # 过程名带下划线（32 位 stdcall 的 C 修饰约定），
            # 导出名由 .def 映射：CloseDriver = _CloseDriver
            # .MODEL FLAT, STDCALL 下 MASM 会自动给过程名加下划线装饰，
            # 因此这里写原名，.def 里做 CloseDriver=_CloseDriver 的映射
            f.write('%s PROC\n    jmp DWORD PTR [p_%s]\n%s ENDP\n'
                    % (n, n, n))
        f.write('\nEND\n')

    with open(os.path.join(here, 'winmm_forward.cpp'), 'w',
              encoding='utf-8', newline='\n') as f:
        f.write('// 本文件由 tools/inject/gen_winmm_proxy.py 自动生成，请勿手改。\n')
        f.write('// 转发桩在 winmm_forward.asm；这里声明符号并解析真实地址。\n')
        f.write('#include <windows.h>\n\n')
        f.write('extern "C" {\n')
        for n in names:
            f.write('extern FARPROC p_%s;\n' % n)
        f.write('}\n\n')
        f.write('extern "C" __declspec(dllexport) void WinmmProxyInit() {\n')
        f.write('  // 必须绝对路径：相对路径依赖当前工作目录，E听说 启动目录不固定\n')
        f.write('  wchar_t sysPath[MAX_PATH];\n')
        f.write('  UINT n = ::GetSystemDirectoryW(sysPath, MAX_PATH);\n')
        f.write('  if (n == 0 || n + 16 >= MAX_PATH) return;\n')
        f.write('  ::wcscat_s(sysPath, MAX_PATH, L"\\\\winmm.dll");\n')
        f.write('  HMODULE real = ::LoadLibraryW(sysPath);\n')
        f.write('  if (real == nullptr) return;\n')
        for n in names:
            f.write('  p_%s = (FARPROC)::GetProcAddress(real, "%s");\n' % (n, n))
        f.write('}\n')
        f.write('extern "C" __declspec(dllexport) void WinmmProxyUninit() {}\n')

    with open(os.path.join(here, 'winmm_forward.def'), 'w',
              encoding='ascii', newline='\n') as f:
        f.write('LIBRARY winmm\nEXPORTS\n')
        for n in names:
            # MASM 在 .MODEL FLAT, STDCALL 下把过程名装饰成 _Name@0（@0 = 声明参数个数）
            f.write('  %s=_%s@0\n' % (n, n))
    print('generated %d forwards -> asm/cpp/def' % len(names))


if __name__ == '__main__':
    main()